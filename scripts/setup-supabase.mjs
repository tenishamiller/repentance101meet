/**
 * Create a DEDICATED Supabase project for Repentance 101 only.
 * Does NOT read credentials from any other project (BraidAppt, etc.).
 *
 * Prerequisites:
 *   1. Create a personal access token at https://supabase.com/dashboard/account/tokens
 *   2. Save it in THIS project's .env.local as SUPABASE_ACCESS_TOKEN=sbp_...
 *
 * Usage:
 *   npm run setup:supabase
 */
import { readFileSync, existsSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const PROJECT_NAME = "repentance101meet";

function loadToken() {
  if (process.env.SUPABASE_ACCESS_TOKEN) return process.env.SUPABASE_ACCESS_TOKEN;

  for (const file of [".env.local", ".env"]) {
    const path = join(root, file);
    if (!existsSync(path)) continue;
    for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
      const m = line.match(/^SUPABASE_ACCESS_TOKEN=(.+)$/);
      if (m) return m[1].replace(/^["']|["']$/g, "");
    }
  }
  return null;
}

const token = loadToken();
if (!token) {
  console.error(`
Missing SUPABASE_ACCESS_TOKEN for Repentance 101 setup.

This project is completely separate from BraidAppt. Use your own token:

  1. Open https://supabase.com/dashboard/account/tokens
  2. Create a token (any name, e.g. "repentance101meet-setup")
  3. Add to repentance101meet/.env.local:

     SUPABASE_ACCESS_TOKEN=sbp_your_token_here

  4. Run: npm run setup:supabase
`);
  process.exit(1);
}

const headers = {
  Authorization: `Bearer ${token}`,
  "Content-Type": "application/json",
};

async function api(path, options = {}) {
  const res = await fetch(`https://api.supabase.com/v1${path}`, {
    ...options,
    headers: { ...headers, ...options.headers },
  });
  const text = await res.text();
  let data;
  try {
    data = text ? JSON.parse(text) : {};
  } catch {
    data = { raw: text };
  }
  if (!res.ok) throw new Error(`${res.status} ${path}: ${text.slice(0, 300)}`);
  return data;
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

console.log(`=== Repentance 101 — dedicated Supabase setup ===\n`);

const orgs = await api("/organizations");
let orgId = process.env.SUPABASE_ORG_ID;
if (orgId) {
  const org = orgs.find((o) => o.id === orgId);
  if (!org) throw new Error(`SUPABASE_ORG_ID not found: ${orgId}`);
  console.log(`Using org from env: ${org.name}`);
} else if (orgs.length === 1) {
  orgId = orgs[0].id;
  console.log(`Using org: ${orgs[0].name}`);
} else {
  console.log("Available organizations:");
  orgs.forEach((o, i) => console.log(`  [${i}] ${o.name} (${o.id})`));
  console.error("\nSet SUPABASE_ORG_ID in .env.local if you have multiple orgs.");
  orgId = orgs[0]?.id;
}

const existing = await api("/projects");
const found = existing.find((p) => p.name === PROJECT_NAME);
let project = found;

const dbPassword = randomBytes(16).toString("base64url").slice(0, 20) + "R101!";
let passwordForConn = dbPassword;

if (!project) {
  console.log(`Creating dedicated Supabase project: ${PROJECT_NAME}...`);
  project = await api("/projects", {
    method: "POST",
    body: JSON.stringify({
      name: PROJECT_NAME,
      organization_id: orgId,
      region: "us-east-1",
      db_pass: dbPassword,
    }),
  });
} else {
  console.log(`Project "${PROJECT_NAME}" already exists (${project.id}).`);
  if (process.env.SUPABASE_DB_PASSWORD) {
    passwordForConn = process.env.SUPABASE_DB_PASSWORD;
  } else {
    console.warn(
      "If connection fails, set SUPABASE_DB_PASSWORD in .env.local to the password you used when creating this project.",
    );
    passwordForConn = dbPassword;
  }
}

const ref = project.ref ?? project.id;
console.log(`Project ref: ${ref}`);

console.log("Waiting for project to become active...");
for (let i = 0; i < 60; i++) {
  const status = await api(`/projects/${ref}`);
  if (status.status === "ACTIVE_HEALTHY") break;
  process.stdout.write(".");
  await sleep(5000);
}
console.log("\nProject active.");

const keys = await api(`/projects/${ref}/api-keys?reveal=true`);
const anonKey = keys.find((k) => k.name === "anon")?.api_key;
const serviceKey = keys.find((k) => k.name === "service_role")?.api_key;

if (!anonKey || !serviceKey) throw new Error("Could not retrieve API keys");

const supabaseUrl = `https://${ref}.supabase.co`;
const authSecret = randomBytes(32).toString("base64");
const encPass = encodeURIComponent(passwordForConn);

const directUrl = `postgresql://postgres.${ref}:${encPass}@aws-0-us-east-1.pooler.supabase.com:5432/postgres`;
const databaseUrl = `postgresql://postgres.${ref}:${encPass}@aws-0-us-east-1.pooler.supabase.com:6543/postgres?pgbouncer=true`;

const envContent = `# Repentance 101 — dedicated environment (NOT shared with BraidAppt)
# Generated by scripts/setup-supabase.mjs

DATABASE_URL="${databaseUrl}"
DIRECT_URL="${directUrl}"
NEXT_PUBLIC_SUPABASE_URL="${supabaseUrl}"
NEXT_PUBLIC_SUPABASE_ANON_KEY="${anonKey}"
SUPABASE_SERVICE_ROLE_KEY="${serviceKey}"

AUTH_SECRET="${authSecret}"
NEXTAUTH_URL="http://localhost:3000"
NEXT_PUBLIC_APP_URL="http://localhost:3000"
NEXT_PUBLIC_APP_NAME="Repentance 101"

ADMIN_EMAIL="norman@repentance101meet.com"
ADMIN_PASSWORD="NormanAdmin2026!"
ADMIN_NAME="Norman"

# LiveKit — create a separate project at cloud.livekit.io for this ministry
LIVEKIT_API_KEY=""
LIVEKIT_API_SECRET=""
LIVEKIT_URL=""
NEXT_PUBLIC_LIVEKIT_URL=""
`;

writeFileSync(join(root, ".env"), envContent);
console.log("Wrote .env (this project only)");

console.log("Creating uploads storage bucket...");
const storageRes = await fetch(`${supabaseUrl}/storage/v1/bucket`, {
  method: "POST",
  headers: {
    Authorization: `Bearer ${serviceKey}`,
    apikey: serviceKey,
    "Content-Type": "application/json",
  },
  body: JSON.stringify({ id: "uploads", name: "uploads", public: true }),
});
if (!storageRes.ok && storageRes.status !== 409) {
  console.warn("Bucket warning:", (await storageRes.text()).slice(0, 200));
} else {
  console.log("Storage bucket ready.");
}

console.log(`
=== Done — 100% separate from BraidAppt ===
Supabase dashboard: https://supabase.com/dashboard/project/${ref}
Project name:       ${PROJECT_NAME}
Database:           dedicated PostgreSQL (own tables, own users)

Next:
  npm run db:push
  npm run db:seed
  npm run dev
`);
